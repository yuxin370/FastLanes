#!/usr/bin/env python3
"""Plot the basic-augmentation training cohort and its resident-input controls."""
import numpy as np
from chart_style import RESULTS, PAPER, BAR_COLORS, BAR_STYLE, HATCHES, plt, read, save

CORE = RESULTS / 'end_to_end/resident/summary.csv'
BASELINES = RESULTS / 'end_to_end/remaining/summary.csv'
SYSTEMS = ['PyTorch', 'DALI', 'CoorDL', 'FFCV', 'FFCV JPEG', 'L3', 'CPU-DCT', 'FastLens']
MODELS = [('vitti', 'ViT-Ti'), ('swinv2', 'SwinV2-T'), ('mobilenet24', 'MV2-24'),
          ('mobilenet32', 'MV2-32'), ('efun', 'eFUN')]
FIGSIZE = (7.0, 1.65)


def training_data():
    core = {(r['gpu'], r['model']): r for r in read(CORE)}
    baseline = {(r['gpu'], r['model'], r['path']): r for r in read(BASELINES)
                if r['phase'] == 'training'}
    data = {}
    for (gpu, model), row in core.items():
        assert int(row['trials']) == 3
        for system, path in [('FFCV', 'ffcv_raw'), ('FFCV JPEG', 'ffcv_jpeg'),
                             ('FastLens', 'imagelanes_basic')]:
            data[gpu, model, system] = tuple(float(row[path + suffix]) for suffix in ('', '_min', '_max'))
        for system, path in [('PyTorch', 'pytorch'), ('DALI', 'dali'), ('CoorDL', 'coordl'),
                             ('L3', 'l3'), ('CPU-DCT', 'cpu_dct')]:
            rgb_model = 'mobilenet24' if model == 'mobilenet32' and path != 'cpu_dct' else model
            result = baseline[gpu, rgb_model, path]
            assert int(result['trials']) == 3
            data[gpu, model, system] = tuple(float(result[k + '_images_per_s']) for k in ('median', 'min', 'max'))
    return data


def plot(axes, systems=SYSTEMS):
    data = training_data()
    x = np.arange(len(MODELS))
    width = .76 / len(systems)
    for ax, gpu in zip(axes, ('4090', 'H100')):
        for i, system in enumerate(systems):
            summaries = np.array([data[gpu, model, system] for model, _ in MODELS])
            medians = summaries[:, 0]
            errors = [medians - summaries[:, 1], summaries[:, 2] - medians]
            label = {'FastLens': 'FastLens DCT', 'CPU-DCT': 'PyTorch DCT',
                     'FFCV': 'FFCV raw RGB'}.get(system, system + ' RGB')
            ax.bar(x + (i - (len(systems) - 1) / 2) * width, medians, width=width * .9,
                   color=BAR_COLORS[system], yerr=errors,
                   error_kw={'elinewidth': .5, 'capsize': 1, 'capthick': .5, 'ecolor': '#333333'},
                   label=label, hatch=HATCHES[system], **BAR_STYLE)
        ax.set_xticks(x, [label for _, label in MODELS], fontsize=7.5)
        ax.tick_params(axis='x', length=0)
        ax.set_title('RTX 4090' if gpu == '4090' else gpu, pad=3)
        ax.grid(axis='y', alpha=.15)
        ax.set_axisbelow(True)
        ax.set_ylim(0, 3200)
        ax.set_yticks([0, 1000, 2000, 3000], ['0', '1k', '2k', '3k'])


def resident_table():
    data = {(r['gpu'], r['model']): r for r in read(CORE)}
    trials = read(CORE.parent/'trials.csv') + [r for r in read(BASELINES.parent/'trials.csv')
                                             if r['phase'] == 'training']
    rates = {(r['gpu'], r['model'], r['path'], int(r['trial'])): float(r['images_per_s'])
             for r in trials}
    rgb_paths = ('pytorch', 'dali', 'coordl', 'l3', 'ffcv_raw', 'ffcv_jpeg')
    lines = [r'% Generated by scripts/plot_deployment_training.py from the resident study.',
             r'\begin{table}[t]', r'\centering\color{red}',
             r'\caption{\textcolor{red}{Training resident throughput (images/s) and attainment relative to each domain\textquotesingle s resident reference. Best RGB takes the fastest of the six RGB paths in each round; DCT uses \sys{}. Throughputs and per-round ratios are three-trial medians; brackets give minimum--maximum ratios.}}',
             r'\label{tab:training-resident}', r'\fontsize{8}{9}\selectfont\setlength{\tabcolsep}{2pt}',
             r'\begin{tabular}{@{}lrrrr@{}}', r'\toprule',
             r'Model & \shortstack{RGB\\resident} & \shortstack{DCT\\resident} & \shortstack{Best RGB\\attainment (\%)} & \shortstack{DCT\\attainment (\%)} \\', r'\midrule']
    for gpu in ('4090', 'H100'):
        lines.append(r'\multicolumn{5}{@{}l}{\textit{' + ('RTX 4090' if gpu == '4090' else gpu) + r'}} \\')
        for model, label in MODELS:
            r = data[gpu, model]
            rgb_model = 'mobilenet24' if model == 'mobilenet32' else model
            attained = [100 * max(rates[gpu, rgb_model, path, trial] for path in rgb_paths)
                        / rates[gpu, rgb_model, 'rgb_resident', trial] for trial in range(3)]
            lines.append(f"{label} & {float(r['rgb_resident']):,.0f} & {float(r['dct_resident']):,.0f} & "
                         f"{np.median(attained):.1f} [{min(attained):.1f}--{max(attained):.1f}] & "
                         f"{100*float(r['E_DCT']):.1f} [{100*float(r['E_DCT_min']):.1f}--{100*float(r['E_DCT_max']):.1f}]" + r' \\')
        lines.append(r'\midrule' if gpu == '4090' else r'\bottomrule')
    lines.extend([r'\end{tabular}', r'\end{table}'])
    (PAPER/'tables/resident_training_results.tex').write_text('\n'.join(lines)+'\n')


def main():
    figure, axes = plt.subplots(1, 2, figsize=FIGSIZE, sharey=True)
    figure.subplots_adjust(left=.065, right=.99, bottom=.22, top=.66, wspace=.12)
    plot(axes)
    axes[0].set_ylabel('Images/s')
    figure.legend(*axes[0].get_legend_handles_labels(), ncol=5, loc='upper center',
                  bbox_to_anchor=(.52, 1), fontsize=7, handlelength=1.2, handletextpad=.3,
                  columnspacing=.7, borderaxespad=0, frameon=False)
    save(figure, 'evaluation/07_deployment_training')
    resident_table()


if __name__ == '__main__':
    main()
