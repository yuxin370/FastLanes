#!/usr/bin/env python3
"""Combine deployment training and inference with one legend and GPU headings."""
import argparse

from chart_style import PAPER, plt, save
from plot_deployment_training import MODELS, SYSTEMS, training_data, plot as plot_training
from plot_deployment_inference import inference_data, plot as plot_inference


def write_tables():
    lines = [r'% Generated by scripts/plot_deployment.py from the same data as the deployment figure.']
    for phase, data, scope in (
        ('Training', training_data(), '65,536-image windows with basic augmentation'),
        ('Inference', inference_data(), 'complete 50,000-image validation passes'),
    ):
        lines.extend([
            r'\begin{table*}[t]',
            r'\centering',
            r'\caption*{\textbf{Author reference: ' + phase.lower()
            + r' deployment throughput (images/s).} Three-trial medians; brackets show minimum--maximum. '
            + phase + ' uses ' + scope + '.}',
            r'\fontsize{8}{9}\selectfont\setlength{\tabcolsep}{3pt}',
            r'\renewcommand{\arraystretch}{1.15}',
            r'\begin{tabular}{@{}lrrrrrrrr@{}}',
            r'\toprule',
            r'Model & \shortstack{PyTorch\\RGB} & \shortstack{DALI\\RGB} & \shortstack{CoorDL\\RGB} & '
            r'\shortstack{FFCV raw\\RGB} & \shortstack{FFCV JPEG\\RGB} & \shortstack{L3\\RGB} & '
            r'\shortstack{PyTorch\\DCT} & \shortstack{\sys{}\\DCT} \\',
            r'\midrule',
        ])
        for gpu in ('4090', 'H100'):
            lines.append(r'\multicolumn{9}{@{}l}{\textit{' + ('RTX 4090' if gpu == '4090' else gpu) + r'}} \\')
            for model, label in MODELS:
                cells = []
                for system in SYSTEMS:
                    median, low, high = data[gpu, model, system]
                    cells.append(r'\shortstack[r]{' + f'{median:,.0f}' + r'\\{\scriptsize['
                                 + f'{low:,.0f}--{high:,.0f}' + r']}}')
                lines.append(label + ' & ' + ' & '.join(cells) + r' \\')
            lines.append(r'\midrule' if gpu == '4090' else r'\bottomrule')
        lines.extend([
            r'\end{tabular}',
            r'\par\smallskip',
            r'\begin{minipage}{\textwidth}\footnotesize',
            r'MV2-24 and MV2-32 reuse the same MobileNetV2 RGB measurements. '
            r'The RGB reference for eFUN is EfficientNet-B0. Values are rounded to whole images/s.',
            r'\end{minipage}',
            r'\end{table*}',
            '',
        ])
    (PAPER / 'tables/deployment_results.tex').write_text('\n'.join(lines))


def main():
    figure, axes = plt.subplots(2, 2, figsize=(7.0, 1.80), sharex=True, sharey="row")
    figure.subplots_adjust(left=.095, right=.99, bottom=.13, top=.81, wspace=.12, hspace=.24)
    plot_training(axes[0])
    plot_inference(axes[1])
    for ax in axes[1]:
        ax.set_title("")
    axes[0, 0].set_ylabel("Training")
    axes[1, 0].set_ylabel("Inference")
    figure.supylabel("Images/s", x=.012, fontsize=8)
    handles, labels = axes[0, 0].get_legend_handles_labels()
    figure.legend(handles, labels, ncol=len(handles), loc="upper center",
                  bbox_to_anchor=(.5, 1), fontsize=7, handlelength=1.1, handletextpad=.3,
                  columnspacing=.6, borderaxespad=0, frameon=False)
    save(figure, "evaluation/08_deployment")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    main()
