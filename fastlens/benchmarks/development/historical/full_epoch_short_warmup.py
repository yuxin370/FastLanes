#!/usr/bin/env python3
"""Run the artifact's single full epoch after excluded page-cache/loader/CUDA warmup.

Pass the train.py arguments generated by run_matrix without --execute, with
--stop-after-epoch 1. The optimizer recipe and epoch implementation are reused.
"""
import json
import os
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[4]
sys.path.insert(0,str(ROOT))


def main():
    import torch
    from fastlens.benchmarks.training_pls import train
    from fastlens.benchmarks.profiling.input_motivation import cache_pages
    from fastlens.benchmarks.system_dct_major.common import parse_manifest
    from fastlens.benchmarks.baselines.system_rgbnomore.training.pipeline import RgbNoMoreTrainingAdapter
    from fastlens.benchmarks.baselines.system_rgbnomore.training.sample_order import SampleIdentity
    from fastlens.benchmarks.training_pls.published_augmentation import published_training_augmentation
    from fastlens.benchmarks.execution.resource_guard import wait_for_input_resources
    args=train._parse_args()
    if args.stop_after_epoch!=1 or args.resume:
        raise ValueError('This driver measures one fresh complete epoch only')
    torch.set_num_threads(8)
    torch.cuda.set_device(args.device)
    device=torch.device(args.device)
    native=args.execution_backend==train.NATIVE_PHYSICAL_BACKEND
    samples,_=train._load_manifest_fast(args.train_manifest,expected_split='train')
    warm_shapes=[64,len(samples)%64 or 64]
    paths=([Path(s['fls_path']) for s in parse_manifest(args.physical_fastlens_manifest)['shards']]
           if native else [s.path for s in samples])
    cache=cache_pages(paths,warm=True)
    if native:
        from fastlens.benchmarks.baselines.system_rgbnomore.shared.paper_adapters import NativeWindow
        loader=NativeWindow('swinv2')
        loader.pipeline.start_epoch(0)
        loader.next_batch()
        loader.close()
    else:
        selected=samples[:64]
        identities=[SampleIdentity(0,i,s.logical_sample_id) for i,s in enumerate(selected)]
        decisions=[published_training_augmentation(training_seed=args.seed,epoch=0,
            logical_sample_id=s.logical_sample_id,virtual_pls_id=0,crop_policy='per-pls',
            source_width=s.width,source_height=s.height).decision for s in selected]
        loader=RgbNoMoreTrainingAdapter(selected,batch_size=64,workers=args.workers,device=device,
            config={'rgbnomore_root':str(args.rgbnomore_root)})
        loader.begin(identities,decisions)
        loader.next_batch()
        loader.close()
    del loader,samples
    compile_original=train.compile_published_model
    warmed=False
    warm_record={}

    def compile_and_warm(model,recipe):
        nonlocal warmed
        execute=compile_original(model,recipe)
        if warmed:
            return execute
        warmed=True
        initial={k:v.detach().cpu().clone() for k,v in model.state_dict().items()}
        initial_hash=train.tensor_state_sha256(initial)
        rng=train.capture_rng_state()
        optimizer,decayer,scheduler=train.build_published_optimizer(model,total_updates=375600)
        for batch_size in warm_shapes:
            inputs=train.example_inputs(args.model,batch_size,device)
            labels=torch.nn.functional.one_hot(torch.arange(batch_size,device=device)%1000,1000).float()
            for _ in range(3):
                optimizer.zero_grad(set_to_none=True)
                lr=scheduler.prepare_next_update()
                with train._autocast_context(recipe,device):
                    logits=execute(*inputs)
                    loss=torch.nn.functional.cross_entropy(logits,labels)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(),1.)
                optimizer.step()
                decayer.step(lr)
                scheduler.complete_update()
                if not bool(torch.isfinite(loss).item()):
                    raise FloatingPointError('Excluded CUDA warmup loss is not finite')
        torch.cuda.synchronize()
        model.load_state_dict(initial)
        model.zero_grad(set_to_none=True)
        train.restore_rng_state(rng)
        if train.tensor_state_sha256(model.state_dict())!=initial_hash:
            raise ValueError('CUDA warmup changed initial model state')
        del initial,optimizer,decayer,scheduler,inputs,labels,logits,loss
        warm_record.update(cache_warm=cache,cuda_warmup_microbatches=6,cuda_warmup_shapes=warm_shapes,
            initial_state_restored=True,initial_model_hash=initial_hash,
            resource_conditions=wait_for_input_resources(os.environ['CUDA_VISIBLE_DEVICES']),
            cpu_affinity=sorted(os.sched_getaffinity(0)),worker_count=args.workers,
            scope='One measured full epoch, excluded short loader warmup and six synthetic CUDA microbatches; no extra warmup epoch')
        before=cache_pages(paths)
        if before['resident_pages']!=before['pages']:
            raise ValueError('Page cache is not fully warm before the full epoch')
        warm_record['cache_before']=before
        # Keep this alongside the artifact run directory, whose file contract is strict.
        args.output_dir.parent.joinpath('short_warmup.json').write_text(json.dumps(warm_record,indent=2)+'\n')
        args.output_dir.parent.joinpath('measurement_active').touch()
        return execute

    train.compile_published_model=compile_and_warm
    result=train.run(args)
    args.output_dir.parent.joinpath('measurement_active').unlink()
    print(json.dumps(result),flush=True)


if __name__=='__main__':
    main()
