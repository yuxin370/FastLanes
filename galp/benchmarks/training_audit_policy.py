#!/usr/bin/env python3
"""Shared fail-closed audit policy for published training benchmarks.

The declarative helpers define the global optimizer-update boundary used by
the current equal-image runners and the checkpoint cursor needed to prove
that resume did not change that boundary.  The compatibility classes at the
end preserve the older benchmark/profiling entry points while those callers
still use their established runtime adapter.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, Iterable, Mapping

if TYPE_CHECKING:
    import torch


AUDIT_POLICY_SCHEMA = "galp-training-audit-policy-v1"
AUDIT_POLICY_VERSION = 1
AUDIT_MODES = ("strict-audit", "runtime-first-100")
DEFAULT_AUDIT_MODE = "runtime-first-100"
DEFAULT_STRICT_UPDATE_COUNT = 100


def _sha256_json(value: Any) -> str:
    encoded = json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def build_audit_policy(
    mode: str = DEFAULT_AUDIT_MODE,
    *,
    strict_update_count: int = DEFAULT_STRICT_UPDATE_COUNT,
) -> dict[str, Any]:
    """Return the immutable policy embedded in all training contracts."""

    mode = str(mode)
    if mode not in AUDIT_MODES:
        raise ValueError(f"unsupported audit mode {mode!r}; expected {AUDIT_MODES}")
    if int(strict_update_count) != DEFAULT_STRICT_UPDATE_COUNT:
        raise ValueError(
            "the published audit boundary is fixed at 100 global optimizer updates"
        )
    runtime = mode == "runtime-first-100"
    payload: dict[str, Any] = {
        "schema_version": AUDIT_POLICY_SCHEMA,
        "audit_policy_version": AUDIT_POLICY_VERSION,
        "audit_mode": mode,
        "strict_update_count": int(strict_update_count),
        "loss_readback_frequency": (
            "every-microbatch"
            if not runtime
            else "every-microbatch-for-updates-1..100; then-fixed-logging-window-or-epoch-boundary"
        ),
        "loss_logits_finite_policy": (
            "synchronous-every-microbatch"
            if not runtime
            else "synchronous-for-updates-1..100; then-device-accumulated-and-read-once-at-epoch-boundary"
        ),
        "gradient_finite_policy": (
            "synchronous-before-every-optimizer-update"
            if not runtime
            else "synchronous-for-updates-1..100; then-device-accumulated-before-clipping-and-read-at-epoch-boundary"
        ),
        "parameter_finite_policy": (
            "synchronous-after-every-optimizer-update"
            if not runtime
            else "synchronous-for-updates-1..100; then-synchronous-at-epoch-boundary"
        ),
        "synchronization_policy": (
            "audit-readback-at-every-microbatch-and-update"
            if not runtime
            else "identical-strict-audit-through-global-update-100; no-per-microbatch-or-per-update-host-readback-afterward"
        ),
        "checked_updates": "all" if not runtime else "global-updates-1..100",
        "deferred_checks": (
            []
            if not runtime
            else [
                "loss-logits-finite-device-accumulator",
                "gradient-finite-device-accumulator",
                "parameter-finite-epoch-boundary",
                "coverage-and-contract-epoch-boundary",
            ]
        ),
        "training_math_invariants": {
            "optimizer_unchanged": True,
            "scheduler_unchanged": True,
            "gradient_accumulation_unchanged": True,
            "gradient_clipping_unchanged": True,
            "numeric_update_order_unchanged": True,
        },
    }
    payload["audit_policy_hash"] = _sha256_json(payload)
    return payload


def validate_audit_policy(policy: Mapping[str, Any]) -> dict[str, Any]:
    """Validate schema, semantic fields, and the policy identity hash."""

    observed = dict(policy)
    if observed.get("schema_version") != AUDIT_POLICY_SCHEMA:
        raise ValueError(
            "training contract has an unsupported/missing audit policy schema; "
            "use a new output directory generated by the current runner"
        )
    mode = str(observed.get("audit_mode", ""))
    strict_count = int(observed.get("strict_update_count", -1))
    expected = build_audit_policy(mode, strict_update_count=strict_count)
    if observed != expected:
        raise ValueError("training audit policy fields/hash differ from the published policy")
    return observed


@dataclass(frozen=True)
class AuditDecision:
    """Audit work for the next one-based global optimizer update."""

    update: int
    strict: bool
    synchronous_loss_logits: bool
    synchronous_gradients: bool
    synchronous_parameters: bool
    per_microbatch_loss_readback: bool


def decision_for_next_update(
    policy: Mapping[str, Any], completed_updates: int
) -> AuditDecision:
    validated = validate_audit_policy(policy)
    completed = int(completed_updates)
    if completed < 0:
        raise ValueError("completed optimizer updates must be non-negative")
    update = completed + 1
    strict = validated["audit_mode"] == "strict-audit" or update <= int(
        validated["strict_update_count"]
    )
    return AuditDecision(
        update=update,
        strict=strict,
        synchronous_loss_logits=strict,
        synchronous_gradients=strict,
        synchronous_parameters=strict,
        per_microbatch_loss_readback=strict,
    )


def audit_cursor(policy: Mapping[str, Any], completed_updates: int) -> dict[str, Any]:
    """Create the checkpointed cursor for an exact global update position."""

    validated = validate_audit_policy(policy)
    completed = int(completed_updates)
    if completed < 0:
        raise ValueError("completed optimizer updates must be non-negative")
    strict_count = int(validated["strict_update_count"])
    checked = (
        completed
        if validated["audit_mode"] == "strict-audit"
        else min(completed, strict_count)
    )
    return {
        "audit_policy_hash": validated["audit_policy_hash"],
        "global_optimizer_update": completed,
        "checked_updates": checked,
        "deferred_updates": completed - checked,
        "next_update_is_strict": decision_for_next_update(
            validated, completed
        ).strict,
    }


def validate_audit_cursor(
    cursor: Mapping[str, Any],
    policy: Mapping[str, Any],
    *,
    completed_updates: int,
) -> dict[str, Any]:
    expected = audit_cursor(policy, completed_updates)
    if dict(cursor) != expected:
        raise ValueError(
            "resume checkpoint audit policy/update cursor differs from the contract"
        )
    return expected


def epoch_audit_summary(
    policy: Mapping[str, Any], *, start_update: int, end_update: int
) -> dict[str, Any]:
    """Describe strict and deferred update coverage within one epoch."""

    validated = validate_audit_policy(policy)
    start = int(start_update)
    end = int(end_update)
    if start < 0 or end < start:
        raise ValueError("invalid epoch audit update interval")
    strict_boundary = (
        end
        if validated["audit_mode"] == "strict-audit"
        else min(end, int(validated["strict_update_count"]))
    )
    checked = max(0, strict_boundary - start)
    total = end - start
    return {
        "audit_mode": validated["audit_mode"],
        "audit_policy_hash": validated["audit_policy_hash"],
        "start_global_optimizer_update_exclusive": start,
        "end_global_optimizer_update_inclusive": end,
        "checked_updates": checked,
        "deferred_updates": total - checked,
        "deferred_checks_executed_at_epoch_boundary": (
            validated["audit_mode"] == "runtime-first-100" and end > 100
        ),
    }


# Compatibility facade for the older benchmark and profiling entry points.
# Keep these names importable without changing those tools' measured runtime
# contract.  New equal-image contracts use build_audit_policy() and
# decision_for_next_update() above.
_COMPAT_AUDIT_MODES = ("strict", "benchmark")


@dataclass(frozen=True)
class TrainingAuditPolicy:
    """Compatibility policy used by established benchmark entry points."""

    mode: str = "benchmark"
    strict_updates: int = DEFAULT_STRICT_UPDATE_COUNT

    def __post_init__(self) -> None:
        if self.mode not in _COMPAT_AUDIT_MODES:
            raise ValueError(f"audit mode must be one of {_COMPAT_AUDIT_MODES}")
        if self.strict_updates < 0:
            raise ValueError("strict_updates must be non-negative")

    def is_strict_update(self, completed_updates: int) -> bool:
        if completed_updates < 0:
            raise ValueError("completed_updates must be non-negative")
        return self.mode == "strict" or completed_updates < self.strict_updates

    def as_contract(self) -> dict[str, Any]:
        return {
            "schema_version": AUDIT_POLICY_SCHEMA,
            "mode": self.mode,
            "strict_updates": self.strict_updates,
            "gradient_finite_check": "before-every-optimizer-step",
            "deferred_finite_boundary": "optimizer-update",
        }

    @classmethod
    def from_contract(
        cls, value: Mapping[str, Any] | None
    ) -> "TrainingAuditPolicy":
        if value is None:
            return cls()
        if value.get("schema_version") != AUDIT_POLICY_SCHEMA:
            raise ValueError("unsupported training audit policy schema")
        policy = cls(
            mode=str(value.get("mode", "")),
            strict_updates=int(value.get("strict_updates", -1)),
        )
        if dict(value) != policy.as_contract():
            raise ValueError("training audit policy contract is not canonical")
        return policy


@dataclass
class TrainingAuditCounters:
    observed_microbatches: int = 0
    strict_microbatches: int = 0
    loss_host_reads: int = 0
    finite_host_reads: int = 0
    gradient_gate_reads: int = 0
    parameter_gate_reads: int = 0

    def as_dict(self) -> dict[str, int]:
        return {
            "observed_microbatches": self.observed_microbatches,
            "strict_microbatches": self.strict_microbatches,
            "loss_host_reads": self.loss_host_reads,
            "finite_host_reads": self.finite_host_reads,
            "gradient_gate_reads": self.gradient_gate_reads,
            "parameter_gate_reads": self.parameter_gate_reads,
        }


@dataclass(frozen=True)
class _DeclarativeAuditPolicyAdapter:
    contract: Mapping[str, Any]

    def is_strict_update(self, completed_updates: int) -> bool:
        return decision_for_next_update(self.contract, completed_updates).strict

    def as_contract(self) -> dict[str, Any]:
        return dict(self.contract)


def _all_finite_device(
    values: Iterable[torch.Tensor], device: torch.device
) -> torch.Tensor:
    import torch

    result = torch.ones((), dtype=torch.bool, device=device)
    found = False
    for value in values:
        found = True
        result.logical_and_(torch.isfinite(value.detach()).all())
    if not found:
        return torch.zeros((), dtype=torch.bool, device=device)
    return result


class TrainingAuditState:
    """Compatibility runtime state for established benchmark loops.

    ``completed_updates`` is the global optimizer update count and is not
    reset at epoch, pool, or backend boundaries.
    """

    def __init__(
        self,
        policy: TrainingAuditPolicy | Mapping[str, Any],
        *,
        completed_updates: int,
        device: torch.device,
    ) -> None:
        import torch

        if completed_updates < 0:
            raise ValueError("completed_updates must be non-negative")
        self._declarative_policy = isinstance(policy, Mapping)
        self.policy = (
            _DeclarativeAuditPolicyAdapter(validate_audit_policy(policy))
            if self._declarative_policy
            else policy
        )
        self.completed_updates = completed_updates
        self.device = device
        self.counters = TrainingAuditCounters()
        self._finite_sticky = torch.ones((), dtype=torch.bool, device=device)
        self._deferred_loss = torch.zeros((), dtype=torch.float64, device=device)
        self._deferred_samples = 0

    @property
    def strict_update(self) -> bool:
        return self.policy.is_strict_update(self.completed_updates)

    def observe(
        self, loss: torch.Tensor, logits: torch.Tensor, sample_count: int
    ) -> float:
        import torch

        if sample_count <= 0:
            raise ValueError("sample_count must be positive")
        self.counters.observed_microbatches += 1
        loss_detached = loss.detach()
        logits_detached = logits.detach()
        if self.strict_update:
            self.counters.strict_microbatches += 1
            self.counters.finite_host_reads += 2
            if not bool(torch.isfinite(loss_detached).item()) or not bool(
                torch.isfinite(logits_detached).all().item()
            ):
                raise FloatingPointError("non-finite loss/logits")
            self.counters.loss_host_reads += 1
            return float(loss_detached.item()) * sample_count

        observed_finite = torch.isfinite(loss_detached) & torch.isfinite(
            logits_detached
        ).all()
        self._finite_sticky.logical_and_(observed_finite)
        self._deferred_loss.add_(loss_detached.to(torch.float64) * sample_count)
        self._deferred_samples += sample_count
        return 0.0

    def check_gradients_and_clip(
        self,
        parameters: Iterable[torch.nn.Parameter],
        *,
        max_norm: float,
    ) -> torch.Tensor:
        import torch

        parameter_list = list(parameters)
        gradients = [
            parameter.grad for parameter in parameter_list if parameter.grad is not None
        ]
        if not gradients:
            raise FloatingPointError("optimizer update has no gradients")
        if self._declarative_policy and not self.strict_update:
            for gradient in gradients:
                self._finite_sticky.logical_and_(
                    torch.isfinite(gradient.detach()).all()
                )
            total_norm = torch.nn.utils.clip_grad_norm_(
                parameter_list,
                max_norm=max_norm,
                error_if_nonfinite=False,
            )
            self._finite_sticky.logical_and_(torch.isfinite(total_norm))
            return total_norm
        total_norm = torch.nn.utils.clip_grad_norm_(
            parameter_list,
            max_norm=max_norm,
            error_if_nonfinite=False,
        )
        update_finite = torch.isfinite(total_norm) & self._finite_sticky
        self.counters.finite_host_reads += 1
        self.counters.gradient_gate_reads += 1
        if not bool(update_finite.item()):
            raise FloatingPointError("non-finite loss, logits, or gradients")
        self._finite_sticky.fill_(True)
        return total_norm

    def complete_update(self) -> None:
        self.completed_updates += 1

    def read_deferred_loss(self) -> tuple[float, int]:
        samples = self._deferred_samples
        if samples == 0:
            return 0.0, 0
        self.counters.loss_host_reads += 1
        value = float(self._deferred_loss.item())
        self._deferred_loss.zero_()
        self._deferred_samples = 0
        return value, samples

    def check_parameters(
        self, parameters: Iterable[torch.nn.Parameter]
    ) -> None:
        finite = _all_finite_device(parameters, self.device)
        self.counters.finite_host_reads += 1
        self.counters.parameter_gate_reads += 1
        if not bool(finite.item()):
            raise FloatingPointError("non-finite model parameters")
